// PRIVATE B2B PAYMENT TICKET ENDPOINTS (Culqi Bridge)
// ==================================================

/**
 * GET /api/client-portal/ticket/:token
 * Retrieves a private payment ticket generated by Admin for corporate card advance/settlement
 */
router.get('/ticket/:token', async (req, res) => {
    try {
        const project = await ClientProject.findOne({
            'paymentTicket.ticketToken': req.params.token,
            'paymentTicket.enabled': true
        });

        if (!project) {
            return res.status(404).json({
                success: false,
                message: 'Ticket de pago privado no encontrado o inactivo.'
            });
        }

        res.json({
            success: true,
            data: {
                otCode: project.otCode,
                projectId: project._id,
                title: project.title,
                clientCompany: project.clientCompany,
                clientName: project.clientName,
                clientEmail: project.clientEmail,
                concept: project.paymentTicket.concept || `Adelanto Corporativo ${project.otCode}`,
                amountPen: project.paymentTicket.amountPen,
                status: project.paymentTicket.status,
                paidAt: project.paymentTicket.paidAt,
                culqiPublicKey: process.env.CULQI_PUBLIC_KEY || ''
            }
        });
    } catch (error) {
        res.status(500).json({ success: false, message: 'Error al consultar ticket de pago.' });
    }
});

/**
 * POST /api/client-portal/ticket/:token/pay
 * Processes a private B2B Culqi charge against an Admin-issued payment ticket
 */
router.post('/ticket/:token/pay', authenticate, async (req, res) => {
    try {
        const { tokenId, email } = req.body;
        const project = await ClientProject.findOne({
            'paymentTicket.ticketToken': req.params.token,
            'paymentTicket.enabled': true
        });

        if (!project) {
            return res.status(404).json({ success: false, message: 'Ticket no encontrado.' });
        }

        if (project.paymentTicket.status === 'paid') {
            return res.status(400).json({ success: false, message: 'Este ticket ya figura como pagado.' });
        }

        if (!process.env.CULQI_SECRET_KEY) {
            return res.status(500).json({
                success: false,
                message: 'Pasarela corporativa no configurada en el servidor. Coordina transferencia directa.'
            });
        }

        const amountCents = Math.round(Number(project.paymentTicket.amountPen) * 100);
        if (!tokenId || amountCents < 300) {
            return res.status(400).json({ success: false, message: 'Monto o token de pago inválido.' });
        }

        const culqiRes = await fetch('https://api.culqi.com/v2/charges', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${process.env.CULQI_SECRET_KEY}`
            },
            body: JSON.stringify({
                amount: amountCents,
                currency_code: 'PEN',
                email: email || req.user.email || project.clientEmail,
                source_id: tokenId,
                description: `Vectore B2B ${project.otCode} - ${project.paymentTicket.concept || project.title}`
            })
        });

        const culqiData = await culqiRes.json();

        if (!culqiRes.ok || culqiData.object === 'error') {
            return res.status(400).json({
                success: false,
                message: culqiData.merchant_message || culqiData.user_message || 'El cargo fue denegado por el banco emisor.'
            });
        }

        project.paymentTicket.status = 'paid';
        project.paymentTicket.paidAt = new Date();
        project.paymentTicket.culqiChargeId = culqiData.id || '';
        await project.save();

        // Also record in Order collection for accounting audit
        await Order.create({
            user: req.user._id,
            items: [{
                name: `${project.otCode} · ${project.paymentTicket.concept || project.title}`,
                price: project.paymentTicket.amountPen,
                quantity: 1
            }],
            subtotal: project.paymentTicket.amountPen,
            total: project.paymentTicket.amountPen,
            status: 'paid',
            paymentMethod: 'culqi_card',
            culqiChargeId: culqiData.id || '',
            culqiTokenId: tokenId,
            culqiResponse: culqiData,
            customerName: project.clientName || req.user.name,
            customerEmail: project.clientEmail,
            paidAt: new Date(),
            notes: `Ticket B2B Privado (${project.clientCompany})`
        }).catch((e) => console.warn('Accounting order log warning:', e.message));

        res.json({
            success: true,
            message: 'Pago corporativo procesado con éxito.',
            data: {
                otCode: project.otCode,
                chargeId: culqiData.id,
                paidAt: project.paymentTicket.paidAt
            }
        });
    } catch (error) {
        console.error('Private B2B ticket payment error:', error);
        res.status(500).json({ success: false, message: 'Error interno al procesar el pago corporativo.' });
    }
});

