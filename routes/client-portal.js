import express from 'express';
import crypto from 'crypto';
import ClientProject from '../models/ClientProject.js';
import Order from '../models/Order.js';
import { authenticate, isAdmin } from '../middleware/auth.js';

const router = express.Router();

// ==================================================
// CLIENT ENDPOINTS (Google OAuth / Corporate Session)
// ==================================================

/**
 * GET /api/client-portal/my-projects
 * Returns all work orders (OTs), HD deliverables, installation reports, invoices & payment tickets for the logged-in client
 */
router.get('/my-projects', authenticate, async (req, res) => {
    try {
        const email = (req.user.email || '').toLowerCase().trim();
        const query = req.user.role === 'admin'
            ? {}
            : { clientEmail: email };

        const projects = await ClientProject.find(query).sort({ updatedAt: -1 });

        res.json({
            success: true,
            data: projects
        });
    } catch (error) {
        console.error('Client portal fetch error:', error);
        res.status(500).json({
            success: false,
            message: 'Error al obtener tus proyectos corporativos.'
        });
    }
});

/**
 * POST /api/client-portal/projects/:id/deliverables/:deliverableId/review
 * Allows a logged-in client to approve high-res artwork or send revision notes
 */
router.post('/projects/:id/deliverables/:deliverableId/review', authenticate, async (req, res) => {
    try {
        const { status, feedback = '' } = req.body;
        if (!['approved', 'changes_requested'].includes(status)) {
            return res.status(400).json({ success: false, message: 'Estado de revisión inválido.' });
        }

        const project = await ClientProject.findById(req.params.id);
        if (!project) {
            return res.status(404).json({ success: false, message: 'Orden de trabajo no encontrada.' });
        }

        const userEmail = (req.user.email || '').toLowerCase().trim();
        if (req.user.role !== 'admin' && project.clientEmail !== userEmail) {
            return res.status(403).json({ success: false, message: 'No tienes permiso para revisar este expediente.' });
        }

        const deliverable = project.deliverables.id(req.params.deliverableId);
        if (!deliverable) {
            return res.status(404).json({ success: false, message: 'Archivo entregable no encontrado.' });
        }

        deliverable.approvalStatus = status;
        deliverable.clientFeedback = feedback.trim();
        deliverable.reviewedAt = new Date();

        if (status === 'approved' && project.status === 'pending_approval') {
            project.status = 'in_production';
            project.progress = Math.max(project.progress, 60);
        }

        await project.save();

        res.json({
            success: true,
            message: status === 'approved'
                ? 'Arte aprobado formalmente. Pasando a cola de producción.'
                : 'Observaciones registradas para el equipo de diseño.',
            data: project
        });
    } catch (error) {
        console.error('Deliverable review error:', error);
        res.status(500).json({ success: false, message: 'No se pudo registrar la revisión.' });
    }
});

