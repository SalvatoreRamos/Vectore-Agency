router.get('/admin/projects', [authenticate, isAdmin], async (req, res) => {
    try {
        const projects = await ClientProject.find().sort({ createdAt: -1 });
        res.json({ success: true, data: projects });
    } catch (error) {
        res.status(500).json({ success: false, message: 'Error al listar expedientes de clientes.' });
    }
});

router.post('/admin/projects', [authenticate, isAdmin], async (req, res) => {
    try {
        const {
            title,
            clientEmail,
            clientName = '',
            clientCompany = '',
            serviceCategory = 'Ejecución BTL & Producción',
            location = 'Pucallpa, Ucayali',
            status = 'in_design',
            progress = 25,
            timelineNotes = '',
            deliverables = [],
            paymentTicket = {}
        } = req.body;

        if (!title || !clientEmail) {
            return res.status(400).json({
                success: false,
                message: 'El título del proyecto y el correo Google del cliente son obligatorios.'
            });
        }

        const project = new ClientProject({
            title: title.trim(),
            clientEmail: clientEmail.trim().toLowerCase(),
            clientName: clientName.trim(),
            clientCompany: clientCompany.trim(),
            serviceCategory,
            location,
            status,
            progress: Number(progress) || 0,
            timelineNotes,
            deliverables: Array.isArray(deliverables) ? deliverables : [],
            paymentTicket: {
                enabled: Boolean(paymentTicket?.enabled),
                concept: paymentTicket?.concept || '',
                amountPen: Number(paymentTicket?.amountPen) || 0,
                status: paymentTicket?.enabled ? (paymentTicket?.status === 'paid' ? 'paid' : 'pending') : 'none',
                ticketToken: paymentTicket?.enabled ? crypto.randomBytes(12).toString('hex') : undefined
            }
        });

        await project.save();

        res.status(201).json({
            success: true,
            message: 'Expediente de cliente creado exitosamente.',
            data: project
        });
    } catch (error) {
        console.error('Admin create client project error:', error);
        res.status(500).json({ success: false, message: 'Error al crear expediente.', error: error.message });
    }
});

router.put('/admin/projects/:id', [authenticate, isAdmin], async (req, res) => {
    try {
        const project = await ClientProject.findById(req.params.id);
        if (!project) {
            return res.status(404).json({ success: false, message: 'Expediente no encontrado.' });
        }

        const {
            title,
            clientEmail,
            clientName,
            clientCompany,
            serviceCategory,
            location,
            status,
            progress,
            timelineNotes,
            deliverables,
            paymentTicket
        } = req.body;

        if (typeof title === 'string') project.title = title.trim();
        if (typeof clientEmail === 'string') project.clientEmail = clientEmail.trim().toLowerCase();
        if (typeof clientName === 'string') project.clientName = clientName.trim();
        if (typeof clientCompany === 'string') project.clientCompany = clientCompany.trim();
        if (typeof serviceCategory === 'string') project.serviceCategory = serviceCategory.trim();
        if (typeof location === 'string') project.location = location.trim();
        if (typeof status === 'string') project.status = status;
        if (typeof progress !== 'undefined') project.progress = Math.min(100, Math.max(0, Number(progress) || 0));
        if (typeof timelineNotes === 'string') project.timelineNotes = timelineNotes.trim();

        if (Array.isArray(deliverables)) {
            project.deliverables = deliverables;
        }

        if (paymentTicket && typeof paymentTicket === 'object') {
            project.paymentTicket.enabled = Boolean(paymentTicket.enabled);
            if (typeof paymentTicket.concept === 'string') project.paymentTicket.concept = paymentTicket.concept.trim();
            if (typeof paymentTicket.amountPen !== 'undefined') project.paymentTicket.amountPen = Number(paymentTicket.amountPen) || 0;
            if (paymentTicket.enabled) {
                if (!project.paymentTicket.ticketToken) {
                    project.paymentTicket.ticketToken = crypto.randomBytes(12).toString('hex');
                }
                if (project.paymentTicket.status === 'none') {
                    project.paymentTicket.status = 'pending';
                }
                if (paymentTicket.status && ['pending', 'paid'].includes(paymentTicket.status)) {
                    project.paymentTicket.status = paymentTicket.status;
                }
            }
        }

        await project.save();

        res.json({
            success: true,
            message: 'Expediente actualizado.',
            data: project
        });
    } catch (error) {
        console.error('Admin update client project error:', error);
        res.status(500).json({ success: false, message: 'Error al actualizar expediente.', error: error.message });
    }
});

router.delete('/admin/projects/:id', [authenticate, isAdmin], async (req, res) => {
    try {
        const project = await ClientProject.findByIdAndDelete(req.params.id);
        if (!project) return res.status(404).json({ success: false, message: 'Expediente no encontrado.' });
        res.json({ success: true, message: 'Expediente eliminado.' });
    } catch (error) {
        res.status(500).json({ success: false, message: 'Error al eliminar expediente.' });
    }
});

export default router;
